USE ROLE ACCOUNTADMIN;

CREATE DATABASE IF NOT EXISTS VEHICLE_DB;
CREATE SCHEMA IF NOT EXISTS VEHICLE_DB.VEHICLE_SCHEMA;
CREATE WAREHOUSE IF NOT EXISTS cnctd_mblty_wh
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE;

USE WAREHOUSE cnctd_mblty_wh;
USE DATABASE VEHICLE_DB;
USE SCHEMA VEHICLE_SCHEMA;

-- Grants (needed for agent/semantic view creation)
GRANT CREATE AGENT ON SCHEMA VEHICLE_DB.VEHICLE_SCHEMA TO ROLE ACCOUNTADMIN;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE ACCOUNTADMIN;

-- ============================================
-- Internal stage for CSV upload
-- ============================================
CREATE OR REPLACE STAGE VEHICLE_DATA_STAGE
  FILE_FORMAT = (TYPE = CSV FIELD_OPTIONALLY_ENCLOSED_BY='"' SKIP_HEADER=1);

